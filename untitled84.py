import pandas as pd
import joblib

from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import OneHotEncoder
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

FEATURES = [
    "Pclass", "Sex", "Age", "SibSp",
    "Parch", "Fare", "Embarked"
]

df = pd.read_csv("train.csv")

# Reserve 31 records that will never be used for model fitting.
development, unseen = train_test_split(
    df, test_size=31, random_state=42,
    stratify=df["Survived"]
)

unseen[["PassengerId"] + FEATURES].to_csv(
    "inference_records.csv", index=False
)

X_train, X_test, y_train, y_test = train_test_split(
    development[FEATURES],
    development["Survived"],
    test_size=0.20,
    random_state=42,
    stratify=development["Survived"]
)

numeric = ["Pclass", "Age", "SibSp", "Parch", "Fare"]
categorical = ["Sex", "Embarked"]

preprocessor = ColumnTransformer([
    ("numeric", SimpleImputer(strategy="median"), numeric),
    ("categorical", Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(handle_unknown="ignore"))
    ]), categorical)
])

model = Pipeline([
    ("preprocessing", preprocessor),
    ("classifier", LogisticRegression(max_iter=1000))
])

model.fit(X_train, y_train)

predictions = model.predict(X_test)
accuracy = accuracy_score(y_test, predictions)

joblib.dump(model, "model.pkl")

print("MODEL TRAINING COMPLETED")
print("Training records:", len(X_train))
print("Testing records:", len(X_test))
print("Reserved inference records:", len(unseen))
print(f"Test accuracy: {accuracy:.4f}")
print(f"Test accuracy: {accuracy * 100:.2f}%")
print("Saved model.pkl")
print("Saved inference_records.csv")

