import matplotlib.pyplot as plt
import numpy as np
import time
import pandas as pd
import joblib

model = joblib.load("model.pkl")
records = pd.read_csv("inference_records.csv")

# Collect real-time streaming simulation results
stream_data = []

print("STREAMING INFERENCE STARTED & LIVE PLOTTING")

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))
plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")

for _, row in records.iloc[21:31].iterrows():
    passenger_id = int(row["PassengerId"])
    features = row.drop(labels=["PassengerId"]).to_frame().T

    prediction = int(model.predict(features)[0])
    prob = model.predict_proba(features)[0][1] * 100
    label = "Survived" if prediction == 1 else "Did not survive"

    stream_data.append({
        "PassengerId": passenger_id,
        "Prediction": prediction,
        "Probability": prob,
        "Label": label
    })

    print(f"Passenger {passenger_id}: {prediction} - {label} (Confidence: {prob:.1f}%)")

    # Live updating plots
    ax1.clear()
    ax2.clear()

    ids = [str(d["PassengerId"]) for d in stream_data]
    probs = [d["Probability"] for d in stream_data]
    colors = ["#2ca02c" if d["Prediction"] == 1 else "#d62728" for d in stream_data]

    # 1. Live Probability Bar Chart
    ax1.bar(ids, probs, color=colors, edgecolor="black")
    ax1.axhline(50, color="gray", linestyle="--", linewidth=1, label="Decision Threshold (50%)")
    ax1.set_title("Live Stream: Survival Probability per Passenger", fontsize=12, fontweight="bold")
    ax1.set_xlabel("Passenger ID")
    ax1.set_ylabel("P(Survived) %")
    ax1.set_ylim(0, 100)
    ax1.tick_params(axis="x", rotation=45)
    ax1.legend(loc="upper right")

    # 2. Cumulative Outcome Ratio
    survived_count = sum(1 for d in stream_data if d["Prediction"] == 1)
    died_count = len(stream_data) - survived_count
    ax2.pie(
        [survived_count, died_count],
        labels=["Survived", "Did not survive"],
        colors=["#2ca02c", "#d62728"],
        autopct="%1.0f%%",
        startangle=90,
        wedgeprops={"edgecolor": "black"}
    )
    ax2.set_title(f"Cumulative Stream Split (Processed: {len(stream_data)}/10)", fontsize=12, fontweight="bold")

    plt.tight_layout()
    plt.pause(0.5)
    time.sleep(1)

print("STREAMING INFERENCE COMPLETED")
plt.show()

